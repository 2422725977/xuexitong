#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 root 手机里把学习通 App 的 WebView cookie 抽出来 → 生成 mooc 域 cookie 文件。

为什么需要它：测试学生账号 fid=0（无学校单位），mooc1 平台按 fid 建会话，签到域 cookie
带不过去（/knowledge/cards、/work/task 全 302 到 passport2 登录页）。要刷网课必须有
「真实学校账号 + mooc 域会话」，而手机上那个 App 已经在用真账号了 —— 直接把它的
WebView cookie 库抠出来，等于复用一次真实登录，不新增设备。

设备侧要求：adb 已连、手机已解锁、Magisk 授权过一次（su -c id 能出 uid=0）。

用法：
  python3 scripts/mooc_cookie_pull.py                 # 拉取 + 解析 + 写 mooc.txt
  python3 scripts/mooc_cookie_pull.py --selftest      # 离线自检（合成 cookie 库）
  python3 scripts/mooc_cookie_pull.py --dump-all      # 顺带列出所有 App 私有 cookie 文件
"""
import argparse, os, re, shutil, sqlite3, subprocess, sys, tempfile

ADB_PARTS = os.environ.get(
    "ADB", "/opt/homebrew/share/android-commandlinetools/platform-tools/adb").split()
PKG = "com.chaoxing.mobile"
THIRD = ("chaoxing.com", "cldisk.com", "chaoxing.cn", "xxt.com")
# WebView cookie 库可能的位置（Chromium 版本不同，目录层级不同）
DB_CANDIDATES = [
    f"/data/data/{PKG}/app_webview/Cookies",
    f"/data/data/{PKG}/app_webview/Default/Cookies",
    f"/data/data/{PKG}/app_webview/Default/Network/Cookies",
    f"/data/data/{PKG}/app_webview/Network/Cookies",
    f"/data/data/{PKG}/app_x5webview/Cookies",
    f"/data/data/{PKG}/app_x5webview/Default/Cookies",
    f"/data/user/0/{PKG}/app_webview/Cookies",
]


def sh(cmd, timeout=60):
    p = subprocess.run(cmd, shell=isinstance(cmd, str), capture_output=True, timeout=timeout)
    return p.returncode, p.stdout, p.stderr


def adb(*args, su=False, binary=False, timeout=60):
    """跑 adb；su=True 时经 su -c 执行（返回 bytes）。"""
    if su:
        # 经 su 时整条命令拼成一个 shell 串，避免引号被 adb 拆散
        cmd = ADB_PARTS + ["shell", "su", "-c", "'" + " ".join(args) + "'"]
    else:
        cmd = ADB_PARTS + list(args)
    p = subprocess.run(cmd, capture_output=True, timeout=timeout)
    if binary:
        return p.returncode, p.stdout
    return p.returncode, p.stdout.decode("utf-8", "ignore"), p.stderr.decode("utf-8", "ignore")


def check_root():
    rc, out, err = adb("id", su=True)
    txt = (out or "") + (err or "")
    if "uid=0" in txt:
        return True, "su OK"
    return False, txt.strip()[:200] or "su 无输出"


def pull_db(remote, local, su=True):
    rc, data = adb(f"cat {remote}", su=su, binary=True)
    if rc != 0 or not data or data[:15] != b"SQLite format 3":
        return False
    with open(local, "wb") as f:
        f.write(data)
    return True


def parse_db(path):
    """返回 [{host,name,value,path,secure}]，跳过空值。"""
    con = sqlite3.connect(path)
    con.row_factory = sqlite3.Row
    try:
        rows = con.execute(
            "SELECT host_key,name,value,encrypted_value,path,is_secure,is_httponly FROM cookies"
        ).fetchall()
    except sqlite3.Error:
        rows = con.execute("SELECT host_key,name,value,path FROM cookies").fetchall()
    out, enc_cnt = [], 0
    for r in rows:
        d = dict(r)
        v = d.get("value") or ""
        if not v:
            ev = d.get("encrypted_value") or b""
            if ev:
                enc_cnt += 1
            continue
        out.append({
            "host": d.get("host_key", ""),
            "name": d.get("name", ""),
            "value": v,
            "path": d.get("path") or "/",
            "secure": bool(d.get("is_secure", 0)),
            "httponly": bool(d.get("is_httponly", 0)),
        })
    con.close()
    return out, enc_cnt


def interesting(cookies):
    return [c for c in cookies if any(t in c["host"] for t in THIRD)]


def to_netscape(cookies, path):
    lines = ["# Netscape HTTP Cookie File", "# generated by mooc_cookie_pull.py"]
    for c in sorted(cookies, key=lambda x: (x["host"], x["name"])):
        host = c["host"]
        # host-only cookie（libcurl/netscape 规则）：域不带前导点，第二列写 FALSE
        dom = host.lstrip(".") if not host.startswith(".") else host
        flag = "TRUE" if dom.startswith(".") else "FALSE"
        sec = "TRUE" if c["secure"] else "FALSE"
        lines.append("\t".join([dom, flag, c["path"] or "/", sec, "0", c["name"], c["value"]]))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(cookies)


def to_header(cookies):
    """按 host 分组，给出可直接塞进 Cookie 头的串（同名取先出现的非空值）。"""
    seen, parts = {}, []
    for c in cookies:
        k = c["name"]
        if k in seen:
            continue
        seen[k] = 1
        parts.append(f"{k}={c['value']}")
    return "; ".join(parts)


KEYS = ["_uid", "UID", "vc3", "fid", "_d", "uf", "lv", "JSESSIONID", "uf_uid", "jrose"]


def report(cookies):
    hosts = {}
    for c in cookies:
        hosts.setdefault(c["host"], 0)
        hosts[c["host"]] += 1
    print(f"[=] 命中 cookie {len(cookies)} 条，分布在 {len(hosts)} 个域：")
    for h, n in sorted(hosts.items(), key=lambda x: -x[1])[:12]:
        print(f"    {h:<45} {n}")
    idx = {}
    for c in cookies:
        idx.setdefault(c["name"], c["value"])
    print("[=] 关键字段：")
    for k in KEYS:
        v = idx.get(k)
        if v is None:
            print(f"    {k:<12} -")
        else:
            shown = v if len(v) <= 12 else v[:8] + "…" + v[-2:]
            print(f"    {k:<12} {shown}")
    return idx


def selftest():
    tmp = tempfile.mkdtemp(prefix="mcpull_")
    db = os.path.join(tmp, "Cookies")
    con = sqlite3.connect(db)
    con.execute("CREATE TABLE cookies (host_key TEXT,name TEXT,value TEXT,encrypted_value BLOB,"
                "path TEXT,is_secure INT,is_httponly INT)")
    rows = [
        (".chaoxing.com", "_uid", "1234567", b"", "/", 0, 1),
        (".chaoxing.com", "vc3", "ZZZsecret", b"", "/", 1, 1),
        ("mooc1.chaoxing.com", "JSESSIONID", "ABCD1234", b"", "/", 0, 0),
        ("pan-yz.chaoxing.com", "uf", "ufval", b"", "/", 0, 0),
        (".example.com", "other", "ignore-me", b"", "/", 0, 0),
        (".chaoxing.com", "emptied", "", b"\x01\x02", "/", 0, 0),
    ]
    con.executemany("INSERT INTO cookies VALUES (?,?,?,?,?,?,?)", rows)
    con.commit()
    con.close()
    allc, enc = parse_db(db)
    assert len(allc) == 5, allc
    assert enc == 1, enc
    mine = interesting(allc)
    assert len(mine) == 4, mine
    ns = os.path.join(tmp, "mooc.txt")
    n = to_netscape(mine, ns)
    assert n == 4
    body = open(ns, encoding="utf-8").read()
    assert "\n.chaoxing.com\tTRUE\t/\tFALSE\t0\t_uid\t1234567" in body, body
    assert "\nmooc1.chaoxing.com\tFALSE\t/\tFALSE\t0\tJSESSIONID\tABCD1234" in body, body
    hdr = to_header(mine)
    assert "_uid=1234567" in hdr and "other=ignore-me" not in hdr
    report(mine)
    shutil.rmtree(tmp, ignore_errors=True)
    print("[+] selftest PASS（解析 / 过滤 / Netscape / Cookie 头 / 关键字段 全部符合预期）")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="mooc.txt", help="Netscape cookie 输出（喂 import_curl.py）")
    ap.add_argument("--header", default="mooc.txt.hdr", help="Cookie 头单行输出")
    ap.add_argument("--port", default=adbserial(), help="adb -s 序列号，默认取唯一设备")
    ap.add_argument("--dump-all", action="store_true", help="列出 App 私有目录里所有可疑 cookie 文件")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.port:
        ADB_PARTS.extend(["-s", a.port])
    try:
        ok, msg = check_root()
    except Exception as e:
        ok, msg = False, f"{type(e).__name__}: {e}"
    if not ok:
        print(f"[x] root 不可用：{msg}")
        print("    手机需要先解锁屏幕，并在 Magisk 弹窗里点一次「允许」（只弹这一次）。")
        return 2
    print(f"[+] {msg}")
    tmp = tempfile.mkdtemp(prefix="mcpull_")
    local = ""
    found = []
    for cand in DB_CANDIDATES:
        dest = os.path.join(tmp, "Cookies." + str(len(found)))
        if pull_db(cand, dest):
            found.append((cand, dest))
            print(f"[+] 拉到 {cand}（{os.path.getsize(dest)} B）")
    if not found:
        print("[x] 没找到 WebView cookie 库 —— 在 App 里随便打开一个课程页（让 WebView 落 cookie）后重试。")
        print("    手机侧探一下：")
        rc, o, e = adb(f"ls -la /data/data/{PKG}/app_webview/ 2>&1 | head -20", su=True)
        print((o + e)[:800])
        return 3
    remote, local = found[0]
    cookies, enc = parse_db(local)
    mine = interesting(cookies)
    if not mine:
        print(f"[!] cookie 库有 {len(cookies)} 条，但没有 chaoxing 域的 —— 在 App 里打开一次课程/视频页再跑。")
    idx = report(mine)
    n = to_netscape(mine, a.out)
    with open(a.header, "w", encoding="utf-8") as f:
        f.write(to_header(mine))
    print(f"[+] 写入 {a.out}（{n} 条 Netscape）与 {a.header}")
    print(f"[=] 加密值 {enc} 条（WebView 若启用 app-bound 加密则拿不到明文，那时改用共享 prefs 路线）")
    if a.dump_all:
        rc, o, e = adb(f"find /data/data/{PKG} -maxdepth 3 -iname '*cookie*' 2>/dev/null | head -30", su=True)
        print("[=] App 私有目录里的 cookie 相关文件：")
        print((o + e)[:1500])
    if idx.get("fid") in (None, "", "0"):
        print("[!] fid 为空/0 —— 这个账号可能没绑学校单位，mooc1 依旧会 302。")
    else:
        print(f"[+] fid={idx.get('fid')} → 下一步：python3 scripts/import_curl.py {a.out} && "
              f"python3 scripts/mooc_probe.py --cookie mooc.txt")
    return 0


def adbserial():
    try:
        p = subprocess.run(ADB_PARTS + ["devices"], capture_output=True, timeout=20)
        devs = re.findall(r"^(\S+)\s+device$", p.stdout.decode("utf-8", "ignore"), re.M)
        if len(devs) == 1:
            return devs[0]
    except Exception:
        pass
    return ""


if __name__ == "__main__":
    sys.exit(main())
